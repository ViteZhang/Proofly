-- =============================================================
-- Proofly · 34 深扫的分批与跳过
--
-- 上游：《商业化 C2》2.3
--
-- 深扫的成本随经历数线性增长，而标价固定 5 分。两条兜住：
--   单次最多扫 10 条（超出分批）
--   扫过且此后没改过的，下次跳过，不重复调模型
--
-- 第二条让第二次扫描便宜很多，而标价不变 —— 对用户是纯赚。
-- =============================================================

alter table atoms
  add column if not exists last_deep_scan_at timestamptz,
  -- 扫的时候这条经历的 updated_at。下次比对：没变就跳过。
  -- 施工提示词写的是 bigint，这里用 timestamptz —— 经历本身没有
  -- 单调计数器，它的版本就是 updated_at，存原值比存一个换算过的
  -- 整数更容易对账。
  add column if not exists last_deep_scan_rev timestamptz;
