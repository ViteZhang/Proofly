-- Proofly · 48 回填出来的履历要标出来
--
-- 由 atoms 按 org 聚合出的起止时间必然偏窄：「在职但那阵子没有可写的
-- 项目」的月份聚合不出来。所以回填只是一个草稿，不是结论。
--
-- needs_review 就是「这条还没人看过」的记号。人在界面上改过一次并保存，
-- 它才清零。没有这个标记的话，一份日期偏窄的简历会以完全正常的样子导
-- 出去 —— 那正是这次改动要消灭的东西。
-- =============================================================

alter table employments add column if not exists needs_review boolean not null default false;
