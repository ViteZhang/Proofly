// =============================================================
// Proofly · 哪些体检项是「上一次生成的产物」
//
// 生成前有一道拦截：体检里还有阻断项就不许生成。它防的是带着已知的
// 事实冲突去印简历 —— 那是输入侧的问题，先解决再生成，顺序是对的。
//
// 但门禁结果也写进同一张 check_results，体检再把它们汇总成 C2–C5。
// 于是出现一个闭环：
//
//   生成 → 门禁拦下 → 结果写进 check_results → 体检报出阻断项
//        → 生成被前置拦截拦住 → 只有生成才能覆盖那些结果 → 回到第一步
//
// 一次失败的生成会永久关掉生成功能，而且失败那一版根本没有写入 ——
// 报出来的问题描述的是一份不存在的简历。用一个动作自己的失败记录去
// 禁止重试这个动作，逻辑上就不成立。
//
// 所以前置拦截只看输入侧的检查。门禁自己那一层的拦截一点没松：生成
// 有 blocking 就不写入、导出返回 409、锁定被拒 —— 它们各自还在。
//
// 纯常量，不连库。
// =============================================================

/** 由门禁结果汇总出来的体检码。它们描述已生成的文本，不是生成的前提。 */
export const GATE_DERIVED_CODES: ReadonlySet<string> = new Set(["C2", "C3", "C4", "C5"]);

/** 这一条是不是「上一次生成留下的」——是的话不参与生成前的拦截。 */
export function isGenerationOutput(origin: string | null, code: string | null): boolean {
  if (origin === "gate") return true;
  return code !== null && GATE_DERIVED_CODES.has(code);
}
