// =============================================================
// Proofly · CHITCHAT 的回复
//
// 固定文案池，不调模型（方案 3.2）。
// 每条都顺带说清这里是干什么的——「你能做什么」也会落到这个分支，
// 池子里随机抽一条如果只是「好的」，那就等于没回。
// =============================================================

const POOL = [
  "嗯，随时说。有进展、拿到数据、或者突然想起来的细节，丢给我就行。",
  "好。项目动了、数字出来了，跟我说一句，我记进经历库。",
  "收到。想更新哪条经历，直接说事就行，不用先找条目。",
  "行。下次有新的进展或者数据，一句话就够。",
];

export function chitchatReply(): string {
  return POOL[Math.floor(Math.random() * POOL.length)];
}
