// =============================================================
// Proofly · 门禁六条各自「该怎么办」
//
// 门禁原来只说哪里不对，不说往哪走。这在 G3 上代价最大：一句
// 「要么是编的，要么是原始记录漏了」看完，人还是不知道该点哪里。
//
// 单独放一个文件，是因为两处要用同一份说法 —— 生成当场被拦的那个
// 红条，和之后一直挂在右侧面板上的那份记录。两处各写一遍，迟早
// 会不一样。
//
// 纯常量，不连库不进模型。
// =============================================================

import type { GateCode } from "./gate";

export const HOW_TO_FIX: Record<GateCode, string> = {
  G1: "要么把这段里的结果数字去掉，要么去那条经历补上实测数据、把证明度提上来。措辞的上限由证明度定，不由文笔定。",
  G2: "这条经历的护栏里禁了这个词。改这一段的措辞，或者去经历里把那条护栏去掉 —— 但先想清楚当初为什么要禁它。",
  G3: "打开那条经历，把这个数字补进 actions 或 metrics；如果它本来就不该出现在简历上，重新生成一次通常就不会再写它。",
  G4: "去基本信息把这一项填完整。它被标成冲突，说明几处材料的说法对不上，简历印哪一个都是错的。",
  G5: "这个技能标签没有任何经历撑得住。去经历库把它挂到一条经历上，或者从技能栏拿掉。",
  G6: "同一个互斥组里有两条经历同时出现了。去「配置经历策略」，把其中一条设成省略。",
};

export function howToFix(code: string | null): string | null {
  return code && code in HOW_TO_FIX ? HOW_TO_FIX[code as GateCode] : null;
}
