/** 8.4 语义冲突 · System */
export const CONFLICT_SYSTEM = `你要在同一件事的多份材料之间，找出**事实层面的矛盾**。

## 什么算矛盾

算：
- 同一个技术选型有两种说法（一处写通义千问，一处写 OpenAI）
- 同一个数字对不上（一处写 4 万 DAU，一处写 40 万）
- 同一段时间对不上（一处写 2025.01 开始，一处写 2024.10 开始）
- 同一个角色对不上（一处写主导，一处写参与）
- 同一件事的状态对不上（一处写已上线，一处写开发中）

**不算**：
- 详略不同（一处展开写，一处一句话带过）
- 措辞不同但意思一致（"AI 模块"与"AI 助手"指同一个东西）
- 视角不同（一处从用户价值讲，一处从技术实现讲）
- 时间推移导致的自然变化（旧文档写"开发中"，新文档写"已上线"——这是进展不是矛盾）

**最后一条最容易误报。** 判断依据是材料的时间先后：如果新材料描述的状态比旧材料更靠后，那是进展；如果反过来，才是矛盾。

## 你的输出会被怎么用

用户会拿着你找出的矛盾去修改自己的求职材料。

**误报的代价很高**——他会花时间去核对一个根本不存在的问题，几次之后就不再信任这个功能了。

所以：**拿不准就不报。** 只报你有把握的、明确的事实矛盾。

## 严重度

- \`high\`：技术选型、核心数字、角色职责的矛盾。这类被面试官问到会直接失信
- \`medium\`：时间、规模、状态的矛盾。可能是记录不及时
- \`low\`：细节描述的出入

## 输出

严格 JSON，无解释文字，无 markdown 围栏。

{
  "conflicts": [
    {
      "subject": "矛盾的对象，如「知识宇宙所用的大模型」",
      "severity": "high|medium|low",
      "statements": [
        {"source": "材料名称", "claim": "该材料的说法，逐字引用不超过 40 字"},
        {"source": "", "claim": ""}
      ],
      "why_conflict": "为什么这是矛盾而不是详略或视角差异，30 字以内",
      "suggested_action": "建议怎么处理，一句话"
    }
  ]
}

没有发现矛盾时输出 {"conflicts": []}。**不要为了显得有用而凑数。**`;

export type ConflictVars = {
  atomJson: string;
  sourceExcerptsJson: string;
  resumeTextsJson: string;
};

/** 8.4 语义冲突 · User */
export function conflictUser(v: ConflictVars): string {
  return `## 经历当前记录的内容
${v.atomJson}
含：title、org、role、period、status、situation、task、actions、metrics。

## 该经历关联的源材料片段
${v.sourceExcerptsJson}
每条含：文档名、上传时间、原文片段。

## 该经历在各方向简历中的表述
${v.resumeTextsJson}
每条含：所属求职方向、简历中的原文。`;
}
